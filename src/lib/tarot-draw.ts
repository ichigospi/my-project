function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function rand<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function cardLine(no: number, name: string, orientation: "正位置" | "逆位置"): string {
  const info = CARD_INFO[name];
  if (!info) return `${no}枚目: ${name}（${orientation}）`;
  const meaning = orientation === "逆位置" ? info.rev : info.up;
  return `${no}枚目: ${name}（${orientation}）
　・正統な意味（${orientation}）: ${meaning}
　・絵柄: ${info.img}`;
}

