// 構成モード: 動画の構成を「いつものテンプレ」で作るか「元ネタの構成を完全トレース」で作るか。
// 元ネタがテンプレと大きく違う場合、骨組みページのポップアップでユーザーが選択する。
// reference選択時も「不変ルール」（文字数・口調・重複禁止など）は据え置きで厳守させる。

export type StructureMode = "template" | "reference";

// 生成系プロンプト（骨組み・台本）に注入する上書きブロック
export function referenceModeBlock(style?: string): string {
  return `
【構成モード: 元ネタ準拠（ユーザー選択・最優先）】
このプロジェクトでは、いつものテンプレ構成ではなく「主軸元ネタの構成」で作ることをユーザーが選択している。
- カテゴリ別ルール・チャンネルルールのうち「動画の構成・進行の型」を定める部分
  （セクションの種類・順番・数、パート構成、オープニングの型、カードの枚数や各カードの役割の型、
  ヒーリング/リーディングの進行テンプレ等）は今回は適用しない
- 代わりに、主軸元ネタの構成（セクションの順番・役割・尺配分・進行）を完全にトレースする
- テンプレ構成と元ネタ構成が矛盾する箇所は、必ず元ネタ構成を優先する
- 【冒頭フックのトレース（必達）】冒頭の掴み・選民フックは、ルールの定型文（「おめでとうございます。このリーディングに辿り着いたあなたは…」等）を使わず、
  主軸元ネタの冒頭フックの型・言い回しをトレースして、自チャンネルの世界観・口調に変換して使うこと。
  ルールの定型文を使ってよいのは、元ネタに冒頭フックが実質存在しない場合の保険としてだけ
- 【コメントCTAのトレース（必達）】コメントCTAの型（何をコメントさせるか・どの位置か・どんな理由づけか）も主軸元ネタをトレースする。
  毎回「予祝・完了形」等の定型に自動で寄せない。サーバー抽選の【コメントCTAの型】【選民・的中の追加演出】【離脱防止】等の割り当ては、
  元ネタに該当する演出が無いパートの補完としてのみ使い、元ネタと競合したら元ネタを優先する
- 【新パターンの提案】元ネタのフック・CTA・離脱防止の型が、ルールや抽選バンクに無い新しい型だった場合は、
  骨組みの末尾に「💡 新パターン提案: 【カテゴリ名】型の名前 — 内容の説明（1〜2行）」を出力すること（オーナーがパターンライブラリへ追加判断できるように）
${style === "tarot" ? "- タロットの場合: カードの抽選結果は引き続き使うが、引く枚数・順番・各カードの役割は元ネタの進行に合わせてよい\n" : ""}
【構成が変わっても据え置きで厳守する不変ルール】
1. 文字数目標（主軸元ネタ±500字。個別指定があればそれに従う）
2. 口調・語彙・キャラ設定（チャンネル共通ルール・固有語彙・NG表現）
3. 同一ワードの連呼禁止・内容/訴求の重複禁止
4. 予祝の定義（理想の未来の「出来事」を先に言葉にする）
5. 時期訴求は今日（現在日時）を基点にする
6. タイトル・テーマの一貫（全セクションをタイトルの具体テーマに紐づける）
7. 重CTAの種類と導線（チャンネル既定の無料鑑定・LINE誘導。終盤の軽→重2段ラダー）
8. 表現品質（不自然な日本語・奇妙な体感表現・嘘くさい誇張の禁止）
`;
}

// 品質チェック系プロンプトに注入する評価基準の切り替えノート
export function referenceModeQcNote(): string {
  return `
【構成モード: 元ネタ準拠（評価基準の切り替え）】
この台本/骨組みは、ユーザー選択により「テンプレ構成ではなく主軸元ネタの構成」で作られている。
- テンプレ構成（進行の型・セクションの種類や順番・カードの枚数の型等）に従っていないこと自体は指摘しない（減点もしない）
- 構成の評価は「主軸元ネタの構成をトレースできているか」を基準にする
- 不変ルール（文字数・口調/語彙・連呼/重複禁止・予祝・時期基準日・テーマ一貫・CTA導線・表現品質）は通常通り厳しく評価する
`;
}
