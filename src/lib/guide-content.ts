// デッキ（この教育で見せる技）。only を付けると、そのバンクの中で見出しに含まれる語に一致する項目だけ
export interface EducationDeck { bankId: string; only?: string[] }
export interface EducationType {
  id: string;
  no: number;
  title: string;
  purpose: string;             // 目的（Notionの解説から。2〜3文でよい）
  place: string;               // 台本のどこで使うか（チップ表示）
  examples: EducationExample[]; // 代表例 1〜2
  points: string[];            // ポイント（最大5つ。オーナーが決める。初期値は空）
  memo: string;                // 解説メモ（オーナーが手入力／指示で追記。初期値は空）
  deck: EducationDeck[];       // この教育で見せる技（技カタログ）
  patternCategories: string[]; // パターンライブラリの該当カテゴリ
  styles: GuideStyle[];
}

